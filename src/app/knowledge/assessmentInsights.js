export const getEnvironmentTaxSummary = (person) => {
  const p = person;
  const dims = ["D", "I", "S", "C"];

  // Preference Tax (confirmed from DISC gaps)
  const gaps = dims.map(d => ({
    dim: d,
    natural: p.disc.natural[d],
    adaptive: p.disc.adaptive[d],
    gap: p.disc.adaptive[d] - p.disc.natural[d],
    absGap: Math.abs(p.disc.adaptive[d] - p.disc.natural[d])
  }));
  const totalGap = gaps.reduce((sum, g) => sum + g.absGap, 0);
  const costlyGaps = gaps.filter(g => g.absGap >= 20);
  const observableGaps = gaps.filter(g => g.absGap >= 10 && g.absGap < 20);

  // Process signals (from Attributes bias patterns)
  const extMinusBiases = p.attr.ext.filter(a => a.bias === "−" || a.bias === "\u2212").length;
  const intMinusBiases = p.attr.int.filter(a => a.bias === "−" || a.bias === "\u2212").length;
  const hasFrustratedPT = p.attr.ext.find(a => a.label === "Hand" && (a.bias === "−" || a.bias === "\u2212"));

  // Compound patterns detected
  const activeCompounds = Object.values(compoundPatterns).filter(cp => cp.check(p));

  return {
    gaps,
    totalGap,
    costlyGaps,
    observableGaps,
    extMinusBiases,
    intMinusBiases,
    hasFrustratedPT,
    activeCompounds
  };
};

// Helper: Get DISC gap insight text
export const getGapInsight = (dim, gap) => {
  const absGap = Math.abs(gap);
  if (absGap < 10) return null;
  const direction = gap > 0 ? "amplified" : "suppressed";
  const severity = absGap >= 20 ? "significant" : "observable";
  return discGapInsights[direction]?.[dim]?.[severity] || null;
};

// Helper: Get bias key normalized (handles both "−" and "\u2212")
export const normalizeBias = (bias) => {
  if (bias === "-" || bias === "−" || bias === "\u2212") return "−";
  return bias;
};

// Helper: Get attribute bias insight
export const getAttrExtBiasInsight = (label, bias) => {
  const norm = normalizeBias(bias);
  return attrExtInsights[label]?.biasInsights?.[norm] || attrExtInsights[label]?.biasInsights?.["="] || null;
};

export const getAttrIntBiasInsight = (name, bias) => {
  const norm = normalizeBias(bias);
  return attrIntInsights[name]?.biasInsights?.[norm] || attrIntInsights[name]?.biasInsights?.["="] || null;
};
